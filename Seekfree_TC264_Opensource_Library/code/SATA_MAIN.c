/*
 * SATA_MAIN.c
 *
 *  主程序：外设初始化 + 主循环 + 每一帧的图像处理
 *
 *  运行结构（对应教程第 13~25 集）：
 *      主循环（约 50fps）  ：大津法二值化 -> 边缘基点 -> 边缘基线 -> 加权中线
 *      5ms 中断（200Hz）   ：编码器测速 -> 速度环 PID -> 差速 -> 电机 PWM
 *                            中线偏差 -> 舵机 PD -> 舵机 PWM
 *      两者通过 midline_info.error 交换数据
 *
 *  Created on: 2026年10月20日
 *      Author: Freed
 */
#include "SATA_MAIN.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     外设初始化
// 参数说明     void
// 返回参数     void
// 使用示例     内部调用
// 备注信息     顺序不能乱：先外设，最后再开控制节拍
//-------------------------------------------------------------------------------------------------------------------
static void SATA_Init(void)
{
    Camera_LCD_Init();                                  // 总钻风 MT9V03X + TFT180
    Badpoint_Init();                                    // 清空边缘基点信息
    Bedline_Init();                                     // 清空边缘基线信息
    MIDLine_Init();                                     // 清空中线信息
    Zebra_Init();                                       // 斑马线起停状态机

    Encoder_Init();                                     // 左右编码器
    Servo_Init();                                       // 舵机 PWM（回中）
    Motor_Init();                                       // 左右电机 PWM（停转）
    Control_Init();                                     // 复位 PID 与状态

    PIT_Init();                                         // 最后启动 5ms 控制节拍
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     单帧图像处理：大津法二值化 -> 基点 -> 基线 -> 加权中线 -> 屏幕叠加
// 参数说明     void
// 返回参数     void
// 使用示例     内部调用
// 备注信息     调用前 mt9v03x_finish_flag 必须已经置 1（DMA 采完一整帧）
//-------------------------------------------------------------------------------------------------------------------
static void SATA_Frame_Process(void)
{
    mt9v03x_finish_flag = 0;                            // 清标志，等下一帧

    Camera_Process_Once();                              // 大津法阈值 -> 二值化 -> 显示二值图像
    Zebra_Scan();                                       // 斑马线判定（必须在二值化之后）

    Find_Badpoint(base_image[0], MT9V03X_W, MT9V03X_H); // 边缘基点
    Find_Bedline (base_image[0], MT9V03X_W, MT9V03X_H); // 边缘基线
    Find_MIDLine ();                                    // 加权求中线值 + 互补滤波

    Badpoint_Show_On_TFT180();                          // 基点十字 + 基点列号
    Bedline_Show_On_TFT180();                           // 基线直线 + 基线斜率
    MIDLine_Show_On_TFT180();                           // 中线（绿色）+ 中线值 + 偏差
    Zebra_Show_On_TFT180();                             // 起停状态 W/R/F
    Control_Show_On_TFT180();                           // 最底部一行轮速（6x8 小字，y=148，不压图像）
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     主程序（由 core0_main 调用，不返回）
// 参数说明     void
// 返回参数     void
// 使用示例     SATA_MAIN();
// 备注信息     1. cpu_wait_event_ready() 必须放在主循环之前，负责和其他核心同步
//              2. 主循环只做"判帧 -> 图像处理"，控制由 5ms 中断完成，互不阻塞
//-------------------------------------------------------------------------------------------------------------------
void SATA_MAIN(void)
{
    SATA_Init();                                        // 1. 外设初始化

    cpu_wait_event_ready();                             // 2. 与其他核心同步（务必保留）

    while(TRUE)                                         // 3. 主循环
    {
        if(mt9v03x_finish_flag)                         // 摄像头采完一帧
        {
            SATA_Frame_Process();                       // 处理这一帧
        }
    }
}
