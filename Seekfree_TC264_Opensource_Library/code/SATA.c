#include "SATA.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化
// 参数说明     void
// 返回参数     void
// 使用示例     SATA_MAIN();
// 备注信息     这里只做初始化，不要写 while(1)
//              否则 cpu0_main 里的 cpu_wait_event_ready() 永远执行不到，CPU1 会一直卡在等待
//-------------------------------------------------------------------------------------------------------------------
void SATA_MAIN(void)
{
    Camera_LCD_Init();
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     单帧处理（放在主循环里反复调用）
// 参数说明     void
// 返回参数     void
// 使用示例     while(TRUE) { SATA_Loop(); }
// 备注信息     mt9v03x_finish_flag 由 DMA 完成中断置 1，必须等它置位再取图，
//              否则拿到的是空缓冲/半帧图像，二值化结果不可信
//-------------------------------------------------------------------------------------------------------------------
void SATA_Loop(void)
{
    if(mt9v03x_finish_flag)
    {
        mt9v03x_finish_flag = 0;                        // 清标志，等下一帧
        Camera_Process_Once();                          // 求阈值 → 二值化 → 显示
    }
}
